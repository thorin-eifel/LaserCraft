#!/usr/bin/env python3
"""Converts the single-stroke Hershey glyphs of LaserGRBL 7.14.1 (Hershey.cs, horizontal set) into a Swift data file.

usage: make_hershey.py <Hershey.cs> <output .swift>
Each glyph becomes "x,y x,y;x,y x,y" (strokes separated by ';'). Units: the glyph box is 2.0 high.
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8-sig")
block = src[src.index("hor ="):src.index("ver =")]
rows = re.findall(r"new string\[\] \{(.*?)\},?\s*$", block, re.M)
assert len(rows) == 95, len(rows)
out = []
for row in rows:
    toks = re.findall(r'"([^"]*)"', row)
    x = y = 0.0
    strokes, cur, down, mode = [], [], False, 0
    maxx = 0.0
    for t in toks:
        if t == "M3":
            down = True; cur = [(x, y)]
        elif t == "M5":
            if len(cur) > 0: strokes.append(cur)
            cur, down = [], False
        else:
            mx = re.search(r"X(-?[\d.]+)", t); my = re.search(r"Y(-?[\d.]+)", t)
            if mx: x = float(mx.group(1))
            if my: y = float(my.group(1))
            maxx = max(maxx, x)
            if t.startswith("G1"): mode = 1
            elif t.startswith("G0"): mode = 0
            if mode == 1 and down: cur.append((x, y))
    if cur: strokes.append(cur)
    enc = ";".join(" ".join(f"{px:g},{py:g}" for px, py in s) for s in strokes)
    out.append((enc, maxx))
lines = ["// Generated by scripts/make_hershey.py from LaserGRBL's Hershey.cs (single-stroke fonts, GPL).", "",
         "enum HersheyData {", "    /// ASCII 32...126: (strokes, advance width). Glyph box is 2 units high.", "    static let glyphs: [(String, Double)] = ["]
for enc, w in out:
    lines.append(f'        ("{enc}", {w:g}),')
lines += ["    ]", "}", ""]
pathlib.Path(sys.argv[2]).write_text("\n".join(lines))
print("glyphs:", len(out))
