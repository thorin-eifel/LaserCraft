#!/usr/bin/env python3
"""Converts LaserGRBL's vendor CSV tables into Sources/LaserGRBLCore/VendorTables.swift.
usage: make_vendor_tables.py <LaserGRBL/CSV folder> <output.swift>"""
import sys, pathlib

csv = pathlib.Path(sys.argv[1])


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rows(name, ncols):
    out = []
    for line in (csv / name).read_text(encoding="utf-8-sig").splitlines():
        if not line.strip():
            continue
        parts = [p.strip() for p in line.split(",", ncols - 1)]
        if not parts[0].isdigit() or len(parts) < ncols:
            continue
        out.append((int(parts[0]), *parts[1:]))
    return out


def emit(var, name, ncols):
    r = rows(name, ncols)
    body = ",\n".join("        (" + ", ".join([str(x[0])] + [q(c) for c in x[1:]]) + ")" for x in r)
    types = ", ".join(["String"] * (ncols - 1))
    return f"    static let {var}: [(Int, {types})] = [\n{body}\n    ]\n"


tables = [
    ("halErrors", "error_codes.ortur.GrblHal.csv", 3), ("halAlarms", "alarm_codes.ortur.GrblHal.csv", 3),
    ("halSettings", "setting_codes.ortur.GrblHal.csv", 4),
    ("longerErrors", "error_codes.longer.nanoduo.csv", 3), ("longerAlarms", "alarm_codes.longer.nanoduo.csv", 3),
    ("longerSettings", "setting_codes.longer.nanoduo.csv", 4),
    ("orturSettings14", "setting_codes.ortur.v1.4.x.csv", 4), ("orturSettings15", "setting_codes.ortur.v1.5.x.csv", 4),
    ("orturSettings17", "setting_codes.ortur.v1.7.x.csv", 4),
]
out = ["// Generated by scripts/make_vendor_tables.py from LaserGRBL's CSV tables (error, alarm and setting codes of other firmwares).", "",
       "enum VendorTables {"]
for v, n, c in tables:
    out.append(emit(v, n, c))
out.append("}\n")
pathlib.Path(sys.argv[2]).write_text("\n".join(out))
print("ok")
